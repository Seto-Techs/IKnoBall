#!/usr/bin/env bun
/**
 * DISC-02: turn the 30 team logos into Discord *application* emojis.
 *
 * `teams.logoUrl` is an SVG and Discord will not render SVG anywhere, so the
 * marks have to become PNGs. Per-guild emoji would need Manage Expressions and
 * 30 uploads per server; application emojis are owned by the bot's application,
 * render in every guild it is in, and need no extra permission on the invite.
 *
 * Pipeline, per team:
 *
 *   teams.logoUrl (SVG) → sharp → 128×128 PNG with a transparent background
 *     → POST /applications/{application.id}/emojis  (name = tricode)
 *     → id collected into `src/cards/team-emojis.ts`
 *
 * Run it with the bot token in the environment:
 *
 *   DISCORD_TOKEN=… bun run apps/discord/scripts/build-team-emojis.ts
 *
 * `--dry-run` fetches and rasterises every logo and prints what it *would* upload
 * and the map it would write, without touching Discord and without writing a
 * file. That is the mode to use when no token is available: it proves the whole
 * conversion half of the pipeline.
 *
 * Re-running is safe: an emoji whose name already exists on the application is
 * reused rather than duplicated, so the id map converges instead of growing.
 */

import { writeFile } from 'node:fs/promises';
import https from 'node:https';
import path from 'node:path';
import { createDatabase, teams } from '@iknoball/database';
import sharp from 'sharp';

/** Discord's application-emoji ceiling is 128px; anything larger is downscaled. */
const EMOJI_SIZE = 128;

const DISCORD_API = 'https://discord.com/api/v10';

/** Application emoji creation is rate-limited; one per second is well inside it. */
const UPLOAD_INTERVAL_MS = 1_000;

const DOWNLOAD_TIMEOUT_MS = 20_000;

const MAP_PATH = path.resolve(__dirname, '../src/cards/team-emojis.ts');

/** Names must be 2–32 chars of `[A-Za-z0-9_]`, which a tricode already is. */
const EMOJI_NAME = /^[A-Za-z0-9_]{2,32}$/;

const MAP_HEADER = `/**
 * Application emoji ids, keyed by team tricode.
 *
 * Generated by \`apps/discord/scripts/build-team-emojis.ts\` — do not edit by
 * hand; re-run the script instead. \`null\` means that team has no uploaded emoji
 * yet, and every card falls back to a plain tricode label so it still renders
 * before the upload has ever run.
 *
 * The emoji is named after the tricode (\`<:LAL:123456789>\`), because that is the
 * only team identifier the schedule, the pick buttons and the emoji name all
 * share.
 */
`;

interface Args {
  dryRun: boolean;
  help: boolean;
  out: string;
}

interface TeamLogo {
  tricode: string;
  name: string;
  logoUrl: string;
}

interface Rasterised extends TeamLogo {
  png: Buffer;
  sourceBytes: number;
}

function parseArgs(argv: string[]): Args {
  const args: Args = { dryRun: false, help: false, out: MAP_PATH };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--dry-run') args.dryRun = true;
    else if (arg === '--help' || arg === '-h') args.help = true;
    else if (arg === '--out') args.out = path.resolve(argv[++index] ?? MAP_PATH);
    else if (arg.startsWith('--out=')) args.out = path.resolve(arg.slice('--out='.length));
    else throw new Error(`Unknown argument "${arg}". See --help.`);
  }

  return args;
}

const USAGE = `Turn the 30 team logos into Discord application emojis and write the id map.

Usage:
  DISCORD_TOKEN=… bun run apps/discord/scripts/build-team-emojis.ts [--dry-run] [--out <path>]

Options:
  --dry-run    Fetch and rasterise every logo, print what would be uploaded and
               the map that would be written. No token needed, nothing written.
  --out <path> Where to write the id map. Defaults to src/cards/team-emojis.ts.
  --help       This text.
`;

/**
 * The 30 clubs, from the same table the web app reads.
 *
 * Ordered by tricode so the generated map is stable across runs and diffs only
 * when an id changes.
 */
async function loadTeams(): Promise<TeamLogo[]> {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL is not set: the script reads the 30 logos from the teams table.');
  }

  const { db, pool } = createDatabase();
  try {
    const rows = await db
      .select({ tricode: teams.abbreviation, name: teams.fullName, logoUrl: teams.logoUrl })
      .from(teams)
      .orderBy(teams.abbreviation);

    const missing = rows.filter((row) => !row.logoUrl);
    for (const row of missing) {
      console.warn(`  ${row.tricode}: no logoUrl, skipping (its emoji id stays null).`);
    }

    return rows
      .filter((row): row is TeamLogo => Boolean(row.logoUrl))
      .map((row) => ({ ...row, logoUrl: row.logoUrl as string }));
  } finally {
    await pool.end();
  }
}

/**
 * `node:https`, not `fetch`.
 *
 * Bun's `fetch` resolves cdn.nba.com over IPv6 first and then hangs until the
 * timeout, because the sandbox has no IPv6 egress; `node:https` gets an IPv4
 * address and answers in milliseconds. This is the one place the script talks to
 * a non-Discord host, so it is the one place that has to care.
 */
function download(url: string): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const request = https.get(url, { headers: { accept: 'image/svg+xml,image/*' } }, (response) => {
      const status = response.statusCode ?? 0;
      if (status !== 200) {
        response.resume();
        reject(new Error(`${url} answered ${status}`));
        return;
      }

      const chunks: Buffer[] = [];
      response.on('data', (chunk: Buffer) => chunks.push(chunk));
      response.on('end', () => resolve(Buffer.concat(chunks)));
      response.on('error', reject);
    });

    request.setTimeout(DOWNLOAD_TIMEOUT_MS, () =>
      request.destroy(new Error(`${url} timed out after ${DOWNLOAD_TIMEOUT_MS}ms`)),
    );
    request.on('error', reject);
  });
}

/**
 * SVG → a 128×128 PNG on transparency.
 *
 * `density` is the rasterisation resolution of the vector: at the default 72 DPI
 * a logo with a long wordmark lands near 128px and is then upscaled, which is
 * exactly the mush DISC-02 warns about. Rendering at 600 DPI and letting
 * `contain` scale down keeps the edges clean.
 */
async function rasterise(svg: Buffer): Promise<Buffer> {
  return sharp(svg, { density: 600 })
    .resize(EMOJI_SIZE, EMOJI_SIZE, {
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();
}

async function discord<T>(
  method: 'GET' | 'POST',
  apiPath: string,
  token: string,
  body?: unknown,
): Promise<T> {
  for (let attempt = 0; ; attempt += 1) {
    const response = await fetch(`${DISCORD_API}${apiPath}`, {
      method,
      headers: { authorization: `Bot ${token}`, 'content-type': 'application/json' },
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: AbortSignal.timeout(30_000),
    });

    if (response.status === 429 && attempt < 2) {
      const payload = (await response.json()) as { retry_after?: number };
      const waitMs = Math.ceil((payload.retry_after ?? 1) * 1_000) + 250;
      console.warn(`  rate limited on ${apiPath}; retrying in ${waitMs}ms`);
      await sleep(waitMs);
      continue;
    }

    if (!response.ok) {
      const detail = (await response.text()).slice(0, 300);
      throw new Error(`${method} ${apiPath} failed with ${response.status}: ${detail}`);
    }

    return (await response.json()) as T;
  }
}

async function applicationId(token: string): Promise<string> {
  // The application's id is the bot user's id; the emoji routes are keyed on it.
  const me = await discord<{ id: string }>('GET', '/users/@me', token);
  return me.id;
}

async function existingEmojis(token: string, application: string): Promise<Map<string, string>> {
  const { items } = await discord<{ items: { id: string; name: string }[] }>(
    'GET',
    `/applications/${application}/emojis`,
    token,
  );

  return new Map(items.map((emoji) => [emoji.name, emoji.id]));
}

async function uploadEmoji(token: string, application: string, name: string, png: Buffer) {
  const { id } = await discord<{ id: string }>(
    'POST',
    `/applications/${application}/emojis`,
    token,
    {
      name,
      image: `data:image/png;base64,${png.toString('base64')}`,
    },
  );

  return id;
}

/** The generated module, byte for byte, so a dry run can show it before it exists. */
function renderMap(ids: Record<string, string | null>): string {
  const entries = Object.keys(ids)
    .sort()
    .map((tricode) => `  ${tricode}: ${ids[tricode] ? `'${ids[tricode]}'` : 'null'},`)
    .join('\n');

  return `${MAP_HEADER}export const TEAM_EMOJI_IDS: Readonly<Record<string, string | null>> = {\n${entries}\n};\n`;
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log(USAGE);
    return;
  }

  const teamLogos = await loadTeams();
  console.log(`Loaded ${teamLogos.length} team logos from the database.`);

  const rasterised: Rasterised[] = [];
  for (const team of teamLogos) {
    if (!EMOJI_NAME.test(team.tricode)) {
      throw new Error(`"${team.tricode}" is not a valid emoji name (2–32 of [A-Za-z0-9_]).`);
    }

    const svg = await download(team.logoUrl);
    const png = await rasterise(svg);
    const meta = await sharp(png).metadata();

    if (meta.width !== EMOJI_SIZE || meta.height !== EMOJI_SIZE || !meta.hasAlpha) {
      throw new Error(
        `${team.tricode}: expected ${EMOJI_SIZE}×${EMOJI_SIZE} with alpha, got ${meta.width}×${meta.height} alpha=${meta.hasAlpha}`,
      );
    }

    rasterised.push({ ...team, png, sourceBytes: svg.length });
    console.log(
      `  ${team.tricode}  ${team.name}: ${svg.length} B SVG → ${png.length} B PNG (${meta.width}×${meta.height}, alpha)`,
    );
  }

  if (args.dryRun) {
    const planned = Object.fromEntries(rasterised.map((team) => [team.tricode, null]));
    console.log(`\nDry run: nothing uploaded, nothing written.`);
    console.log(
      `Would POST ${rasterised.length} emojis to ${DISCORD_API}/applications/{application.id}/emojis.`,
    );
    console.log(`Would write ${args.out} as:\n`);
    console.log(renderMap(planned));
    return;
  }

  const token = process.env.DISCORD_TOKEN?.trim();
  if (!token) {
    throw new Error(
      'DISCORD_TOKEN is not set. Re-run with --dry-run to convert without uploading.',
    );
  }

  const application = await applicationId(token);
  const existing = await existingEmojis(token, application);
  console.log(`\nApplication ${application} already has ${existing.size} emoji.`);

  const ids: Record<string, string | null> = {};
  for (const team of rasterised) {
    const found = existing.get(team.tricode);
    if (found) {
      ids[team.tricode] = found;
      console.log(`  ${team.tricode}: reusing ${found}`);
      continue;
    }

    ids[team.tricode] = await uploadEmoji(token, application, team.tricode, team.png);
    console.log(`  ${team.tricode}: uploaded ${ids[team.tricode]}`);
    await sleep(UPLOAD_INTERVAL_MS);
  }

  await writeFile(args.out, renderMap(ids), 'utf8');

  const uploaded = Object.values(ids).filter(Boolean).length;
  console.log(`\nWrote ${args.out} with ${uploaded}/${rasterised.length} ids.`);
}

main().catch((error: unknown) => {
  console.error(`\n${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
});
